<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require dirname(__DIR__).'/bootstrap.php';
use Monitor\Services\PublicStatus;
$results=[];
$ok=static function (bool $truth,string $label)use(&$results):void{$results[]=[$truth,$label];};
$root=monitor_root();
$up=['is_active'=>1,'operational_status'=>'up'];
$down=['is_active'=>1,'operational_status'=>'down'];
$pending=['is_active'=>1,'operational_status'=>'unknown'];
$paused=['is_active'=>0,'operational_status'=>'up'];
$ok(PublicStatus::overall([],[])==='none','Empty status is not operational');
$ok(PublicStatus::overall([$up],[])==='operational','Single up service operational');
$ok(PublicStatus::overall([$up,$up],[])==='operational','All public active services up');
$ok(PublicStatus::overall([$down],[])==='major','All down major disruption');
$ok(PublicStatus::overall([$down,$down],[])==='major','All down multi major disruption');
$ok(PublicStatus::overall([$up,$down],[])==='issues','Partial outage');
$ok(PublicStatus::overall([$pending],[])==='pending','Unknown status pending');
$ok(PublicStatus::overall([$up,$pending],[])==='pending','Mixed known and unknown not green');
$ok(PublicStatus::overall([$paused],[])==='pending','All paused not green');
$ok(PublicStatus::overall([$up,$paused],[])==='pending','Paused status not silently ignored');
$ok(PublicStatus::overall([$paused],[['started_at'=>'2026-10-31 00:00:00']])==='issues','Paused open incident remains visible');
$ok(PublicStatus::monitorLabel($up)[0]==='Operational','Up badge');
$ok(PublicStatus::monitorLabel($down)[0]==='Outage','Down badge');
$ok(PublicStatus::monitorLabel($pending)[0]==='Status Pending','Unknown badge');
$ok(PublicStatus::monitorLabel($paused)[0]==='Monitoring Paused','Paused badge');
$ok(str_contains(PublicStatus::metadata('major','Acme')[0],'Major Service Disruption'),'Status-aware page title');
$ok(str_contains(PublicStatus::metadata('operational','Acme')[0],'Acme'),'White label metadata');
$ok(!str_contains(PublicStatus::metadata('issues','Acme')[0],'Persisca'),'No developer credits');
$ok(PublicStatus::dailyState(0,0)==='no_data','Unobserved day not green');
$ok(PublicStatus::dailyState(0,0,true)==='paused','Current paused empty day');
$ok(PublicStatus::dailyState(0,0,false,60)==='partial','Confirmed outage without samples');
$ok(PublicStatus::dailyState(10,10)==='operational','Recorded all successful day');
$ok(PublicStatus::dailyState(10,9)==='partial','Mixed success day partial');
$ok(PublicStatus::dailyState(10,0)==='outage','All failed day outage');
$ok(PublicStatus::dailyState(10,10,false,180)==='partial','Incident time overrides apparently green samples');
$at=new DateTimeImmutable('2026-10-31 09:01:00',new DateTimeZone('UTC'));
$days=PublicStatus::days(new DateTimeZone('America/Vancouver'),$at);
$ok(count($days)===30,'Exactly 30 days');
$ok(array_key_last($days)==='2026-10-31','Local current day included');
$ok(array_key_first($days)==='2026-10-02','Local 30 day span');
$ok(array_sum(array_map(static fn($x)=>$x['checks'],$days))===0,'Empty day history has no fake samples');
$ok(count(PublicStatus::days(new DateTimeZone('Asia/Kolkata'),$at))===30,'Half-hour timezone supported');
$ok(PublicStatus::zone('Invalid/Zone')->getName()==='UTC','Invalid timezone safe fallback');
$service=file_get_contents($root.'/app/Services/PublicStatus.php');
$view=file_get_contents($root.'/app/Views/public/status.php');
$controller=file_get_contents($root.'/public/index.php');
$admin=file_get_contents($root.'/admin/_dispatch.php');
$schema=file_get_contents($root.'/database/schema.sql');
$sql=file_get_contents($root.'/database/patches/v0.0.7.sql');
$ok(str_contains($service,'WHERE is_public=1 AND portal_user_id'),'Public monitors explicitly filtered');
$ok(substr_count($service,'m.is_public=1')===2,'Both incident lists public only');
$ok(!str_contains($service,'SELECT *'),'No unbounded wildcard public select');
$ok(!str_contains($view,'monitor_url'),'Internal monitor URL not displayed');
$ok(!str_contains($view,'error_message'),'Raw curl errors not displayed');
$ok(!str_contains($view,'telegram'),'Telegram secrets not displayed');
$ok(str_contains($view,'sp-history-grid'),'History bars rendered');
$ok(str_contains($view,'aria-label'),'Accessible history labels');
$ok(str_contains($view,'tabindex="0"'),'Keyboard focusable bars');
$ok(str_contains($view,'Recent incidents'),'Resolved public incidents section');
$ok(str_contains($view,'Active incidents'),'Active incidents section');
$ok(str_contains($view,'refresh this page') || str_contains(strtolower($view),'refresh this page'),'No fake realtime claim');
$ok(str_contains($controller,"absolute_url('status/')"),'Clean canonical route');
$ok(str_contains($controller,'PublicStatus::metadata'),'Dynamic OG metadata');
$ok(str_contains($controller,'status_page_enabled'),'Public visibility toggle honored');
$ok(str_contains($view,'og:image'),'Image preserved');
$ok(str_contains($view,'twitter:card'),'Social image card');
$ok(str_contains($view,'$settings[\'logo_path\']'),'White-label logo');
$ok(str_contains($view,'$settings[\'favicon_path\']'),'White-label favicon');
$ok(str_contains($admin,'if ($page === \'status-page\')'),'Admin Status POST handler') ;
$ok(str_contains($admin,'Settings::putMany($values)'),'Status settings persisted');
$ok(str_contains($admin,"'status-page' => 'status-page'"),'Admin status view attached');
$ok(is_file($root.'/app/Views/admin/status-page.php'),'Status admin screen exists');
$ok(str_contains($sql,'ON DUPLICATE KEY UPDATE setting_key'),'Existing settings remain unchanged');
$ok(!str_contains($sql,'DROP TABLE')&&!str_contains($sql,'TRUNCATE'),'SQL migration non-destructive');
$ok(str_contains($sql,"'v0.0.7'"),'Migration version updated');
$ok(str_contains(file_get_contents($root.'/install/index.php'),'v0.2.2'),'Fresh installer version');
$ok(str_contains(file_get_contents($root.'/app/Models/Settings.php'),"'status_show_incidents' => '1'"),'Installer defaults include status page settings');
$ok(str_contains($schema,'CREATE TABLE IF NOT EXISTS monitor_hourly_stats'),'Stage 06 aggregates kept');
$ok(str_contains($schema,'uniq_notification_recipient_event'),'Multi Chat ID schema kept');
$ok(trim(file_get_contents($root.'/VERSION'))==='v0.2.2','Version updated');
$failed=0;
foreach($results as [$pass,$name]){if(!$pass)$failed++;echo ($pass?'PASS':'FAIL').' '.$name.PHP_EOL;}
echo(count($results)-$failed).'/'.count($results).' passed'.PHP_EOL;
exit($failed?1:0);
