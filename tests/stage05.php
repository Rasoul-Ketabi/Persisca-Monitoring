<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require dirname(__DIR__) . '/bootstrap.php';

use Monitor\Services\NotificationManager;
use Monitor\Services\TelegramNotifier;
use Monitor\Services\MonitorInput;
use Monitor\Services\IncidentManager;

$checks = [];
$ok = static function (bool $pass, string $name) use (&$checks): void { $checks[] = [$pass, $name]; };
$root = monitor_root();
$settings = ['telegram_enabled' => '1', 'telegram_notify_down' => '1', 'telegram_notify_recovery' => '1', 'telegram_bot_token' => '123456789:AAAAAAAAAAAAAAAAAAAAAAAA', 'telegram_chat_id' => '-1001112223334'];
$monitor = ['id' => 5, 'telegram_notifications_enabled' => 1];
$down = ['transition'=>'down', 'incident_id'=>32];
$recovery = ['transition'=>'recovered', 'incident_id'=>32];
$ok(NotificationManager::eligible($monitor,$down,$settings), 'Down transition eligible with valid configuration');
$ok(NotificationManager::eligible($monitor,$recovery,$settings), 'Recovery transition eligible');
$ok(!NotificationManager::eligible($monitor,['transition'=>'none','incident_id'=>32],$settings), 'Steady state cannot alert');
$ok(!NotificationManager::eligible($monitor,['transition'=>'up','incident_id'=>32],$settings), 'Initial Up cannot alert');
$ok(!NotificationManager::eligible($monitor,['transition'=>'down','incident_id'=>null],$settings), 'Missing incident cannot alert');
$off = $settings; $off['telegram_enabled']='0';
$ok(!NotificationManager::eligible($monitor,$down,$off), 'Global disable blocks Down');
$ok(!NotificationManager::eligible($monitor,$recovery,$off), 'Global disable blocks Recovery');
$off = $settings; $off['telegram_notify_down']='0';
$ok(!NotificationManager::eligible($monitor,$down,$off), 'Down toggle blocks only Down');
$ok(NotificationManager::eligible($monitor,$recovery,$off), 'Down toggle preserves Recovery');
$off = $settings; $off['telegram_notify_recovery']='0';
$ok(!NotificationManager::eligible($monitor,$recovery,$off), 'Recovery toggle blocks Recovery');
$ok(NotificationManager::eligible($monitor,$down,$off), 'Recovery toggle preserves Down');
$off=$settings; $off['telegram_bot_token']='';
$ok(!NotificationManager::eligible($monitor,$down,$off), 'Missing Bot Token blocks alert');
$off=$settings; $off['telegram_chat_id']='';
$ok(!NotificationManager::eligible($monitor,$down,$off), 'Missing Chat ID blocks alert');
$off=$monitor; $off['telegram_notifications_enabled']=0;
$ok(!NotificationManager::eligible($off,$down,$settings), 'Per-monitor disable blocks alert');
$ok(TelegramNotifier::validTokenShape('12345:AbCdEfG01234567890_abc'), 'Token shape allows bot token');
$ok(!TelegramNotifier::validTokenShape('https://api.telegram.org/bot1234:secret'), 'Token must not be URL');
$ok(!TelegramNotifier::validTokenShape('12345:bogus value'), 'Token rejects spaces');
$ok(!TelegramNotifier::validTokenShape(''), 'Empty token rejected');
$ok(TelegramNotifier::validChatIdShape('-1001234567890123'), 'Negative group Chat ID accepted');
$ok(TelegramNotifier::validChatIdShape('123456789'), 'Personal Chat ID accepted');
$ok(TelegramNotifier::validChatIdShape('@channelname'), 'Channel name accepted');
$ok(!TelegramNotifier::validChatIdShape('foo bar'), 'Unsafe Chat ID rejected');
$ok(TelegramNotifier::escape('<b>x&"') === '&lt;b&gt;x&amp;&quot;', 'Markup escaping for dynamic text');
$entry=['event_type'=>'down', 'monitor_name'=>'<Suspicious> & Main', 'monitor_url'=>'https://example.com/?a=1&b=2', 'started_at'=>'2026-10-31 12:00:00', 'detected_at'=>'2026-10-31 12:05:00', 'recovered_at'=>'2026-10-31 12:15:00', 'duration_seconds'=>900, 'last_error_type'=>'Request Timeout', 'opening_attempts'=>3, 'recovery_http'=>200, 'recovery_response'=>184];
$msg=TelegramNotifier::message($entry, 'Company & Brand', 'UTC');
$ok(str_contains($msg,'&lt;Suspicious&gt; &amp; Main'), 'Down message escapes monitor name');
$ok(str_contains($msg,'a=1&amp;b=2'), 'Down message escapes URL');
$ok(str_contains($msg,'Company &amp; Brand'), 'Down message uses escaped configured brand');
$ok(str_contains($msg,'is DOWN'), 'Down message includes Down state');
$ok(str_contains($msg,'Attempts: 3'), 'Down message includes attempt count');
$ok(str_contains($msg,'Request Timeout'), 'Down message includes error type');
$ok(str_contains($msg,'Oct 31, 2026 12:05 UTC'), 'Down timestamp uses chosen timezone');
$ok(str_contains(TelegramNotifier::message($entry,'My App','America/Vancouver'),'05:05 PDT'), 'Message timezone conversion works');
$entry['event_type']='recovered'; $msg=TelegramNotifier::message($entry,'My Brand','UTC');
$ok(str_contains($msg,'is back online'), 'Recovery message uses recovery event');
$ok(str_contains($msg,'Downtime: 15 minutes'), 'Recovery uses actual duration');
$ok(str_contains($msg,'Last response: HTTP 200'), 'Recovery includes real HTTP result');
$ok(str_contains($msg,'Response time: 184 ms'), 'Recovery includes response time');
$ok(str_contains($msg,'My Brand'), 'Recovery honors brand');
$ok(!str_contains($msg,'Request Timeout'), 'Recovery does not include stale failure reason');
$good=['name'=>'API','url'=>'https://example.org/','is_active'=>'1','check_interval_minutes'=>'5','timeout_seconds'=>'10','expected_status_codes'=>'200','retry_count'=>'2','retry_delay_seconds'=>'2','failure_threshold'=>'2','telegram_notifications_enabled'=>'1'];
$ok(MonitorInput::fromPost($good)['telegram_notifications_enabled']===1, 'Monitor form enables Telegram flag');
unset($good['telegram_notifications_enabled']);
$ok(MonitorInput::fromPost($good)['telegram_notifications_enabled']===0, 'Unchecked flag disables monitor Telegram');
$prior=['operational_status'=>'up','consecutive_failures'=>0,'failure_threshold'=>2];
$pending=IncidentManager::decide($prior,false,'2026-10-31 10:00:00');
$ok($pending['transition']==='none','Sub-threshold failure has no alert event');
$confirmed=IncidentManager::decide(array_merge($prior,['consecutive_failures'=>1,'failure_sequence_started_at'=>'2026-10-31 10:00:00']),false,'2026-10-31 10:05:00');
$ok($confirmed['transition']==='down','Incident engine still provides confirmed Down');
$ok(IncidentManager::decide(array_merge($prior,['operational_status'=>'down','consecutive_failures'=>2]),false,'2026-10-31 10:10:00')['transition']==='none','Continued outage cannot cause duplicate event');
$ok(IncidentManager::decide(['operational_status'=>'down','consecutive_failures'=>2],true,'2026-10-31 10:15:00')['transition']==='recovered','Incident engine retains recovery transition');
$schema=file_get_contents($root.'/database/schema.sql'); $patch=file_get_contents($root.'/database/patches/v0.0.5.sql');
$ok(str_contains($schema,'CREATE TABLE IF NOT EXISTS notification_logs'),'Fresh installer schema includes notification logs');
$ok(str_contains($patch,'CREATE TABLE IF NOT EXISTS notification_logs'),'Upgrade SQL creates logs');
$ok(str_contains($patch,'ADD COLUMN telegram_notifications_enabled'),'Upgrade adds per-monitor toggle');
$ok(str_contains($schema,'telegram_notifications_enabled TINYINT(1) NOT NULL DEFAULT 1'),'Fresh schema includes toggle');
$ok(str_contains($patch,'UNIQUE KEY uniq_notification_incident_event (channel, incident_id, event_type)'), 'Database idempotency unique key');
$ok(str_contains($patch,'idx_notification_due (status, next_attempt_at)'), 'Retry scheduling index');
$ok(str_contains($patch,'ON DELETE CASCADE'),'Deletion cascades notification history');
$ok(!str_contains($patch,'DROP TABLE') && !str_contains($patch,'TRUNCATE'),'Upgrade migration is nondestructive');
$ok(str_contains($patch,"('telegram_enabled','0'"),'Global Telegram defaults disabled');
$ok(str_contains($patch,"('installed_version', 'v0.0.5'"),'Migration updates installed version');
$ok(str_contains($schema,'CREATE TABLE IF NOT EXISTS incidents'),'Full schema preserves prior incidents');
$repo=file_get_contents($root.'/app/Models/CheckRepository.php');
$ok(str_contains($repo,'NotificationManager::enqueue($pdo, $current, $transition)') && str_contains($repo,'$pdo->commit()'),'Outbox enqueue is inside incident transaction');
$ok(strpos($repo,'NotificationManager::enqueue')<strpos($repo,'$pdo->commit()'), 'Event is persisted before commit');
$ok(str_contains($repo,'catch (Throwable $notificationError)'),'Outbox errors do not abort incident persistence');
$cron=file_get_contents($root.'/app/Services/CronRunner.php');
$ok(str_contains($cron,'NotificationManager::deliverDue(3, $started + self::TARGET_SECONDS)'), 'Cron runs bounded delivery queue');
$ok(str_contains($cron,'catch (Throwable $deliveryError)'), 'Telegram failure isolated from cron');
$manager=file_get_contents($root.'/app/Services/NotificationManager.php');
$ok(str_contains($manager,'attempt_count<3'), 'Retry attempts have finite cap');
$ok(str_contains($manager,"status='processing'"), 'Claim lease used for sends');
$ok(str_contains($manager,'next_attempt_at'), 'Notification retry timestamps supported');
$ok(str_contains($manager,'DATE_ADD(UTC_TIMESTAMP(),INTERVAL 5 MINUTE)'), 'Processing recovery lease is time bounded');
$ok(str_contains($manager,'status=\'failed\''), 'Exhausted processing leases become terminal');
$api=file_get_contents($root.'/app/Services/TelegramNotifier.php');
$ok(str_contains($api,'CURLOPT_SSL_VERIFYPEER => true'), 'Telegram SSL certificate verification enabled');
$ok(str_contains($api,'CURLOPT_SSL_VERIFYHOST => 2'), 'Telegram hostname verification enabled');
$ok(str_contains($api,'CURLOPT_FOLLOWLOCATION => false'), 'Telegram requests do not follow redirects');
$ok(str_contains($api,'CURLOPT_POST => true'), 'Telegram sendMessage uses POST');
$ok(str_contains($api,"str_replace(\$token, '[redacted]'"), 'Provider error redacts bot token');
$ok(str_contains($api,'16384'), 'Telegram API response is bounded');
$dispatch=file_get_contents($root.'/admin/_dispatch.php');
$ok(str_contains($dispatch,"\$page === 'notifications'") && str_contains($dispatch,'Security::requireCsrf()'),'Notifications actions are CSRF-protected');
$ok(str_contains($dispatch,"\$action === 'test'") && !str_contains($dispatch,'TelegramNotifier::send($token, $chat, $result'), 'Connection test has independent action');
$view=file_get_contents($root.'/app/Views/admin/notifications.php');
$ok(str_contains($view,'value="" autocomplete="new-password"'), 'Token not rendered in edit input');
$ok(str_contains($view,'Send Test Message'), 'Connection test UI exists');
$ok(str_contains($view,'notificationPages'), 'Delivery history has pagination');
$ok(!str_contains(file_get_contents($root.'/app/Services/IncidentManager.php'),'Telegram'),'Incident engine remains Telegram-agnostic');
$ok(!str_contains(file_get_contents($root.'/app/Views/public/status.php'),'telegram_bot_token'), 'Public status does not expose token');
$ok(trim(file_get_contents($root.'/VERSION'))==='v0.2.2','VERSION is v0.0.8');
$ok(str_contains(file_get_contents($root.'/install/index.php'),'v0.2.2'),'Installer initializes v0.0.8');
$ok(is_file($root.'/admin/notifications/index.php'),'Physical folder route preserved');
$ok(!str_contains($view,'?page='),'Notifications does not restore old routing');
$ok(!str_contains($view,'Powered by Persisca'),'White-label notifications UI has no developer brand');
$passed=0;
foreach ($checks as [$pass,$label]) { echo ($pass ? 'PASS ' : 'FAIL ') . $label . "\n"; if ($pass) $passed++; }
echo $passed . '/' . count($checks) . " passed\n";
exit($passed === count($checks) ? 0 : 1);
