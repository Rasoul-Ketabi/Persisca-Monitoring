<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require dirname(__DIR__).'/bootstrap.php';
use Monitor\Services\MonitorAnalytics;
use Monitor\Services\RetentionManager;
$tests=[];
$check=static function(bool $condition,string $label) use (&$tests):void{$tests[]=[$condition,$label];};
$root=monitor_root();
$check(trim(file_get_contents($root.'/VERSION'))==='v0.2.2','Stage 06 functionality preserved in v0.0.8');
$check(MonitorAnalytics::period('24h')==='24h','24h selection');
$check(MonitorAnalytics::period('7d')==='7d','7d selection');
$check(MonitorAnalytics::period('30d')==='30d','30d selection');
$check(MonitorAnalytics::period('90d')==='24h','Unsupported range blocked');
$check(MonitorAnalytics::period("24h' OR 1=1")==='24h','SQL interval injection blocked');
$check(MonitorAnalytics::percentage(8,10)===80.0,'Real sample ratio');
$check(MonitorAnalytics::percentage(1,3)===33.33,'Uptime precision');
$check(MonitorAnalytics::percentage(0,0)===null,'No-data is not 100 percent');
$check(MonitorAnalytics::percentage(10,10)===100.0,'Complete sample success');
$check(uptime_label(null)==='Not enough data','No-data formatting');
$check(uptime_label(100.0)==='100%','100% formatted');
$check(uptime_label(99.987)==='99.99%','Rounded formatting');
$check(response_label(null)==='No data','No response data');
$check(response_label(123.1)==='123 ms','Milliseconds formatted');
$check(response_label(1234.0)==='1.23 s','Seconds formatted');
$check(MonitorAnalytics::unionSeconds([[10,20]],0,30)===10,'Single incident duration');
$check(MonitorAnalytics::unionSeconds([[10,20]],15,30)===5,'Incident clipped at start');
$check(MonitorAnalytics::unionSeconds([[10,40]],15,30)===15,'Incident clipped both ends');
$check(MonitorAnalytics::unionSeconds([[10,20],[15,25]],0,30)===15,'Overlap not double counted');
$check(MonitorAnalytics::unionSeconds([[1,3],[5,8],[7,10]],0,12)===7,'Disjoint and overlapping windows');
$check(MonitorAnalytics::unionSeconds([],0,50)===0,'Empty incident set');
$check(MonitorAnalytics::unionSeconds([[1,10]],20,30)===0,'Outside period contributes zero');
$check(RetentionManager::validDays('90')===90,'Retention default validation');
$check(RetentionManager::validDays('2')===90,'Too-short retention denied');
$check(RetentionManager::validDays('garbage')===90,'Unexpected retention rejected');
$check(RetentionManager::validDays('3650')===3650,'Retention upper bound accepted');
$schema=file_get_contents($root.'/database/schema.sql');
$patch=file_get_contents($root.'/database/patches/v0.0.6.sql');
$check(str_contains($schema,'CREATE TABLE IF NOT EXISTS monitor_hourly_stats'),'Fresh schema has hourly stats');
$check(str_contains($patch,'CREATE TABLE IF NOT EXISTS monitor_hourly_stats'),'Migration creates hourly stats');
$check(str_contains($patch,'ON DELETE CASCADE'),'Aggregate rows deleted with monitor');
$check(!str_contains($patch,'DROP TABLE')&&!str_contains($patch,'TRUNCATE'),'Migration is non-destructive');
$check(str_contains($patch,'notification_log_retention_days'),'Log retention seeded');
$check(str_contains($patch,"'v0.0.6'"),'Installed metadata advanced');
$check(str_contains($schema,'uniq_notification_recipient_event'),'Multi-chat unique key remains');
$check(str_contains($schema,'CREATE TABLE IF NOT EXISTS incidents'),'Incident schema remains');
$check(str_contains($schema,'CREATE TABLE IF NOT EXISTS monitor_checks'),'Scheduled history remains');
$check(str_contains($root.'','monitor')!==false,'Tests bootstrapped');
$check(is_file($root.'/admin/monitors/analytics/index.php'),'Folder style analytics route exists');
$check(str_contains(file_get_contents($root.'/admin/_dispatch.php'),"'monitors/analytics'"),'Analytics route registered');
$check(str_contains(file_get_contents($root.'/app/Services/CronRunner.php'),'HourlyAggregator::process'),'Cron builds aggregates');
$check(str_contains(file_get_contents($root.'/app/Services/CronRunner.php'),'RetentionManager::runIfDue'),'Cron performs retention');
$check(str_contains(file_get_contents($root.'/app/Services/RetentionManager.php'),'hourly_aggregated_check_id'),'Cleanup gated on aggregation');
$check(str_contains(file_get_contents($root.'/app/Services/RetentionManager.php'),"i.status='resolved'"),'Unresolved incident delivery logs retained');
$check(str_contains(file_get_contents($root.'/app/Services/MonitorAnalytics.php'),"check_type='scheduled'"),'Only scheduled checks count');
$check(str_contains(file_get_contents($root.'/app/Services/MonitorAnalytics.php'),"COUNT(response_time_ms)"),'Null response durations excluded');
$check(str_contains(file_get_contents($root.'/app/Services/HourlyAggregator.php'),'beginTransaction'),'Aggregate progress is transactional');
$check(str_contains(file_get_contents($root.'/app/Views/admin/monitor-analytics.php'),'Not enough response-time data'),'Chart empty state implemented');
$check(str_contains(file_get_contents($root.'/app/Views/admin/monitor-analytics.php'),'polyline'),'SVG chart implemented');
$check(str_contains(file_get_contents($root.'/app/Views/admin/monitor-analytics.php'),'Sample uptime'),'Sample method is transparent');
$check(str_contains(file_get_contents($root.'/app/Views/admin/dashboard.php'),'fleetAnalytics'),'Dashboard uses factual check metrics');
$check(str_contains(file_get_contents($root.'/app/Models/Settings.php'),"'notification_log_retention_days' => '90'"),'Retention has safe default');
$check(str_contains(file_get_contents($root.'/app/Views/admin/general.php'),'notification_log_retention_days'),'Admin retention edit exists');
$check(str_contains(file_get_contents($root.'/admin/_dispatch.php'),"'notification_log_retention_days' => [7,3650]"),'Server-side retention validation');
$check(str_contains(file_get_contents($root.'/app/Views/admin/system.php'),'ANALYTICS & RETENTION'),'Health page shows analytics');
$check(str_contains(file_get_contents($root.'/app/Views/admin/monitor-detail.php'),'monitors/analytics'),'Details analytics link');
$check(str_contains(file_get_contents($root.'/app/Models/CheckRepository.php'),'NotificationManager::enqueue'),'Existing Telegram event logic retained');
$check(str_contains(file_get_contents($root.'/app/Models/Settings.php'),"'telegram_chat_id'"),'Multi-chat config remains');
$failed=0;
foreach($tests as [$pass,$label]){if (!$pass) $failed++;echo ($pass?'PASS':'FAIL').' '.$label.PHP_EOL;}
echo (count($tests)-$failed).'/'.count($tests).' passed'.PHP_EOL;
exit($failed?1:0);
